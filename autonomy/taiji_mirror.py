#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
卦爻镜像模块 · 接入九转玄功引擎
从卦爻原生引擎v1.0移植核心逻辑，作为九转引擎的状态观察镜像
定位：不参与决策，只做状态映射——把九转的每次任务完成映射为卦爻一轮
守弱原则：小而稳，弱而久。只读九转任务结果，不反向影响九转
守三缺：不做性能优化、不做错误自动修复、不做外部扩展接口
"""
import os
import json
import time
from pathlib import Path
from datetime import datetime

# ==================== 路径配置 ====================
基础目录 = Path(__file__).parent.parent
状态目录 = 基础目录 / "data"
状态文件 = 状态目录 / "taiji_mirror_state.json"

# ==================== 八卦接口定义 ====================
八卦名 = ["震", "兑", "离", "乾", "巽", "坎", "艮", "坤"]
卦象符号 = {"震": "☳", "兑": "☱", "离": "☲", "乾": "☰", "巽": "☴", "坎": "☵", "艮": "☶", "坤": "☷"}
卦义表 = {
    "震": "外来触", "兑": "对外应", "离": "望气显", "乾": "极值亢",
    "巽": "外部渗", "坎": "坑为薪", "艮": "止留缺", "坤": "散余藏",
}

# ==================== 默认状态 ====================
默认状态 = {
    "版本": "九转镜像v0.1",
    "启动时间": None,
    "最后心跳": None,
    "总轮次": 0,
    "成功轮次": 0,
    "失败轮次": 0,
    "连续失败": 0,
    "丹藏": [],
    "炉底秽": [],
    "偏爻记录": [],
    "丹藏上限": 9,
    "单丹份数上限": 3,
    "炉底上限": 5,
    "当前卦位": "震",
    "四象相位": "少阳",
    "炉中气": "纯阴无阳太极初判",
    "最大连续失败": 3,
    "九转转数映射": 0,
    "最近任务": None,
}

太极炉 = None


def 加载状态():
    global 太极炉
    if 状态文件.exists():
        try:
            with open(状态文件, "r", encoding="utf-8") as f:
                太极炉 = json.load(f)
            return
        except Exception:
            pass
    太极炉 = 默认状态.copy()
    太极炉["启动时间"] = datetime.now().strftime("%Y-%m-%d %H:%M:%S")


def 保存状态():
    太极炉["最后心跳"] = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    with open(状态文件, "w", encoding="utf-8") as f:
        json.dump(太极炉, f, ensure_ascii=False, indent=2)


# ==================== 选择压力机制 ====================
def 凝丹(任务名, 成果):
    同名丹 = next((丹 for 丹 in 太极炉["丹藏"] if 丹["任务名"] == 任务名), None)
    if 同名丹:
        同名丹["份数"] = min(同名丹["份数"] + 1, 太极炉["单丹份数上限"])
        同名丹["最后更新"] = datetime.now().strftime("%H:%M:%S")
    else:
        if len(太极炉["丹藏"]) >= 太极炉["丹藏上限"]:
            太极炉["丹藏"].pop(0)
        太极炉["丹藏"].append({
            "任务名": 任务名,
            "成果摘要": str(成果)[:50],
            "份数": 1,
            "凝丹时间": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        })


def 入坑(错误信息):
    if len(太极炉["炉底秽"]) >= 太极炉["炉底上限"]:
        太极炉["炉底秽"].pop(0)
    太极炉["炉底秽"].append(f"{错误信息} @ {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    太极炉["偏爻记录"].append(f"{错误信息} @ {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")


# ==================== 八卦接口（简化版，只做状态流转） ====================
def 震接口(任务名):
    太极炉["当前卦位"] = "震"
    太极炉["四象相位"] = "少阳"


def 兑接口(任务名, 成功):
    太极炉["当前卦位"] = "兑"
    if 成功:
        太极炉["四象相位"] = "老阳"
    else:
        入坑(f"兑接口：任务{任务名}执行失败")


def 离接口(任务名, 成功):
    太极炉["当前卦位"] = "离"
    if not 成功:
        入坑(f"离接口：任务{任务名}校验未通过")


def 乾接口():
    太极炉["当前卦位"] = "乾"
    触顶 = 太极炉["连续失败"] >= 太极炉["最大连续失败"]
    if 触顶:
        入坑(f"乾接口极值触发：连续失败{太极炉['连续失败']}次")
        太极炉["连续失败"] = 0


def 巽接口():
    太极炉["当前卦位"] = "巽"
    太极炉["四象相位"] = "少阴"


def 坎接口():
    太极炉["当前卦位"] = "坎"


def 艮接口(任务名, 成功, 成果):
    太极炉["当前卦位"] = "艮"
    if 成功:
        凝丹(任务名, 成果)


def 坤接口():
    太极炉["当前卦位"] = "坤"
    太极炉["四象相位"] = "老阴"
    太极炉["炉中气"] = f"第{太极炉['总轮次']}轮完成·阴阳冲和"


# ==================== 核心更新接口（九转主循环调用） ====================
def update(task_name, success, result=None, zhuan_count=0):
    """
    九转引擎每次任务完成后调用此函数
    task_name: 任务名称
    success: 是否成功
    result: 任务成果（可选，用于凝丹摘要）
    zhuan_count: 当前九转转数（用于映射）
    """
    global 太极炉
    if 太极炉 is None:
        加载状态()

    太极炉["总轮次"] += 1
    太极炉["最近任务"] = task_name
    太极炉["九转转数映射"] = zhuan_count

    try:
        # 八卦流转（简化为顺序执行，不做递归，避免性能开销）
        震接口(task_name)
        兑接口(task_name, success)
        离接口(task_name, success)
        乾接口()
        巽接口()
        坎接口()
        艮接口(task_name, success, result)
        坤接口()

        if success:
            太极炉["成功轮次"] += 1
            太极炉["连续失败"] = 0
        else:
            太极炉["失败轮次"] += 1
            太极炉["连续失败"] += 1
    except Exception as e:
        太极炉["失败轮次"] += 1
        太极炉["连续失败"] += 1
        入坑(f"镜像更新异常：{str(e)}")

    保存状态()
    return 太极炉["当前卦位"], 太极炉["四象相位"]


def get_status():
    """获取当前卦爻镜像状态"""
    if 太极炉 is None:
        加载状态()
    return {
        "总轮次": 太极炉["总轮次"],
        "成功轮次": 太极炉["成功轮次"],
        "失败轮次": 太极炉["失败轮次"],
        "当前卦位": 太极炉["当前卦位"],
        "四象相位": 太极炉["四象相位"],
        "丹藏数": len(太极炉["丹藏"]),
        "炉底数": len(太极炉["炉底秽"]),
        "九转转数映射": 太极炉["九转转数映射"],
        "最近任务": 太极炉["最近任务"],
    }


# 模块加载时自动恢复状态
加载状态()
