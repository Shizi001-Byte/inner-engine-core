            content = task["generator"]()
            # 估算token
            char_count = len(content)
            chinese_count = sum(1 for c in content if '\u4e00' <= c <= '\u9fff')
            other_count = char_count - chinese_count
            tokens_est = int(chinese_count * 1.5 + other_count * 0.3)

            # 确保在合理范围内
            low, high = TASK_TOKEN_RANGE[self.engine_name]
            tokens_est = max(low, min(high, tokens_est))

            # 写入输出文件
