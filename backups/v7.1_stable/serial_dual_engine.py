def main():
    parser = argparse.ArgumentParser(description="串行双引擎断点续跑调度器")
    parser.add_argument("--duration", type=int, default=DEFAULT_DURATION,
                        help=f"运行时长（秒），默认{DEFAULT_DURATION}")
    parser.add_argument("--engine", choices=["guanchenzi", "xingjuan"], default=None,
                        help="只跑指定引擎（默认串行自动切换）")
    parser.add_argument("--status", action="store_true", help="只显示状态，不运行")
    parser.add_argument("--reset", action="store_true", help="重置断点状态")
    args = parser.parse_args()

    # 信号处理
    signal.signal(signal.SIGTERM, _signal_handler)
    signal.signal(signal.SIGINT, _signal_handler)

    # 确保目录存在
    STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    LOG_FILE.parent.mkdir(parents=True, exist_ok=True)

    checkpoint = CheckpointManager(STATE_FILE)

    if args.reset:
        checkpoint.reset()
        print("断点状态已重置")
        return

    if args.status:
        print(checkpoint.progress_summary())
        return

    runner = SerialRunner(duration=args.duration, engine_override=args.engine)
    runner.run()


if __name__ == "__main__":
    main()
