    def generate_task(self) -> dict:
        """生成一个任务"""
        if self.engine_name == "guanchenzi":
            template = random.choice(GUANCHENZI_TASK_TEMPLATES)
        else:
            template = random.choice(XINGJUAN_TASK_TEMPLATES)

