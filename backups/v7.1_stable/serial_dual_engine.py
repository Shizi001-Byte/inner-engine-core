class SerialRunner:
    """串行双引擎调度器 —— 观尘子先跑，达标/时间到再切星卷"""

    def __init__(self, duration: int, engine_override: str = None):
        self.checkpoint = CheckpointManager(STATE_FILE)
        self.timer = SandboxTimer(duration)
        self.engine_override = engine_override
        self.executors = {
            "guanchenzi": TaskExecutor("guanchenzi"),
            "xingjuan": TaskExecutor("xingjuan"),
        }

    def _select_engine(self) -> str:
        """选择当前应该跑的引擎"""
        if self.engine_override:
            return self.engine_override

        current = self.checkpoint.state["current_engine"]

        # 如果当前引擎已达标，切换
        if self.checkpoint.is_daily_target_met(current):
            other = "xingjuan" if current == "guanchenzi" else "guanchenzi"
            if not self.checkpoint.is_daily_target_met(other):
                _log(f"{'观尘子' if current=='guanchenzi' else '星卷'}已达标，切换到{'星卷' if other=='xingjuan' else '观尘子'}")
                self.checkpoint.switch_engine(other)
                return other

        return current

    def run(self):
        """主循环"""
        _log("=" * 60)
        _log("串行双引擎断点续跑调度器 启动")
        _log(f"沙箱安全窗口: {self.timer.duration}秒 ({self.timer.duration//60}分{self.timer.duration%60}秒)")
        _log(f"每日目标: 观尘子 {DAILY_TARGETS['guanchenzi']:,} + 星卷 {DAILY_TARGETS['xingjuan']:,} = {TOTAL_DAILY_TARGET:,}")
        _log("=" * 60)

        # 打印当前进度
        print(self.checkpoint.progress_summary())

        # 检查是否全部达标
        if self.checkpoint.is_all_target_met():
            _log("🎉 两个引擎今日目标均已达成！无需继续运行。")
            return

        tasks_this_session = 0
        tokens_this_session = 0

        try:
            while _running and not self.timer.is_expired():
                # 全部达标则退出
                if self.checkpoint.is_all_target_met():
                    _log("🎉 两个引擎今日目标均已达成！")
                    break

                # 时间不够接新任务了
                if not self.timer.is_safe_to_start_task():
                    _log(f"剩余时间不足（{self.timer.remaining_str()}），进入收尾模式，不再接新任务")
                    break

                # 选择引擎
                engine_name = self._select_engine()
                executor = self.executors[engine_name]
                display = "观尘子" if engine_name == "guanchenzi" else "星卷"

                # 生成并执行任务
                task = executor.generate_task()
                _log(f"[{display}] 开始任务: {task['name']} (id={task['task_id']})")

                success, tokens, output_path = executor.execute(task)

                if success:
                    self.checkpoint.record_task(engine_name, task["task_id"], tokens, True)
                    tasks_this_session += 1
                    tokens_this_session += tokens
                    eng_state = self.checkpoint.get_engine_state(engine_name)
                    target = DAILY_TARGETS[engine_name]
                    pct = min(100, eng_state["tokens_used"] / target * 100)
                    _log(f"[{display}] ✅ 完成: {task['name']} | +{tokens:,} tokens | 累计{eng_state['tokens_used']:,}/{target:,} ({pct:.1f}%)")
                else:
                    self.checkpoint.record_task(engine_name, task["task_id"], 0, False)
                    _log(f"[{display}] ❌ 失败: {task['name']}")

                # 每5个任务打印一次进度
                if tasks_this_session % 5 == 0:
                    print(f"\n--- 本次会话进度: {tasks_this_session}任务, +{tokens_this_session:,} tokens, 剩余{self.timer.remaining_str()} ---")
                    print(self.checkpoint.progress_summary())

                # 短暂休息，避免CPU满载
                time.sleep(0.3)

        except KeyboardInterrupt:
            _log("收到中断信号，保存断点...")
        except Exception as e:
            _log(f"调度器异常: {e}")
            import traceback
            _log(traceback.format_exc())
        finally:
            # 确保状态保存
            self.checkpoint.save()

        # 会话总结
        _log("=" * 60)
        _log(f"本次会话结束")
        _log(f"  运行时长: {self.timer.elapsed_str()}")
        _log(f"  执行任务: {tasks_this_session} 个")
        _log(f"  消耗token: {tokens_this_session:,}")
        _log(f"  累计总token: {self.checkpoint.state['total_tokens']:,} / {TOTAL_DAILY_TARGET:,}")
        _log(f"  断点已保存，下次激活将自动续跑")
        _log("=" * 60)
        print(self.checkpoint.progress_summary())


