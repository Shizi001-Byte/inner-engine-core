class CheckpointManager:
    """状态实时落盘，沙箱重启后自动恢复"""

    def __init__(self, state_path: Path):
        self.state_path = state_path
        self.state = self._load()

    def _default_state(self):
        today = date.today().isoformat()
        return {
            "date": today,
            "current_engine": "guanchenzi",
            "engines": {
                "guanchenzi": {
                    "tokens_used": 0,
                    "tasks_completed": 0,
                    "last_task_id": None,
                    "consecutive_failures": 0,
                },
                "xingjuan": {
                    "tokens_used": 0,
                    "tasks_completed": 0,
                    "last_task_id": None,
                    "consecutive_failures": 0,
                },
            },
            "total_tokens": 0,
            "total_tasks": 0,
            "session_count": 0,
            "last_update": None,
            "history": [],  # 最近20条任务记录
        }

    def _load(self):
        if not self.state_path.exists():
            return self._default_state()
        try:
            with open(self.state_path, "r", encoding="utf-8") as f:
                state = json.load(f)
            # 跨天自动重置
            today = date.today().isoformat()
            if state.get("date") != today:
                _log(f"检测到跨天（上次={state.get('date')}，今天={today}），自动重置每日计数")
                new_state = self._default_state()
                new_state["session_count"] = state.get("session_count", 0) + 1
                return new_state
            return state
        except Exception as e:
            _log(f"状态文件损坏，重新初始化: {e}")
            return self._default_state()

    def save(self):
        self.state["last_update"] = datetime.now().isoformat()
        self.state_path.parent.mkdir(parents=True, exist_ok=True)
        tmp = self.state_path.with_suffix(".tmp")
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(self.state, f, ensure_ascii=False, indent=2)
        tmp.replace(self.state_path)

    def reset(self):
        self.state = self._default_state()
        self.save()
        _log("断点状态已重置")

    def get_engine_state(self, engine_name: str) -> dict:
        return self.state["engines"][engine_name]

    def record_task(self, engine_name: str, task_id: str, tokens_used: int, success: bool):
        eng = self.state["engines"][engine_name]
        eng["tasks_completed"] += 1
        eng["tokens_used"] += tokens_used
        eng["last_task_id"] = task_id
        if success:
            eng["consecutive_failures"] = 0
        else:
            eng["consecutive_failures"] += 1

        self.state["total_tokens"] += tokens_used
        self.state["total_tasks"] += 1

        # 历史记录（保留最近20条）
        self.state["history"].append({
            "time": datetime.now().strftime("%H:%M:%S"),
            "engine": engine_name,
            "task_id": task_id,
            "tokens": tokens_used,
            "success": success,
        })
        if len(self.state["history"]) > 20:
            self.state["history"] = self.state["history"][-20:]

        self.save()

    def switch_engine(self, engine_name: str):
        self.state["current_engine"] = engine_name
        self.save()

    def is_daily_target_met(self, engine_name: str) -> bool:
        eng = self.state["engines"][engine_name]
        return eng["tokens_used"] >= DAILY_TARGETS[engine_name]

    def is_all_target_met(self) -> bool:
        return all(self.is_daily_target_met(e) for e in DAILY_TARGETS)

    def progress_summary(self) -> str:
        lines = []
        lines.append("=" * 55)
        lines.append(f"  串行双引擎进度  日期: {self.state['date']}")
        lines.append("=" * 55)
        for name, target in DAILY_TARGETS.items():
            eng = self.state["engines"][name]
            used = eng["tokens_used"]
            pct = min(100, used / target * 100)
            bar_len = 30
            filled = int(bar_len * pct / 100)
            bar = "█" * filled + "░" * (bar_len - filled)
            display = "观尘子" if name == "guanchenzi" else "星卷"
            lines.append(f"  {display:4s} |{bar}| {pct:5.1f}%")
            lines.append(f"        {used:>10,} / {target:>10,} tokens  ({eng['tasks_completed']}个任务)")
        total = self.state["total_tokens"]
        total_pct = min(100, total / TOTAL_DAILY_TARGET * 100)
        lines.append("-" * 55)
        lines.append(f"  合计  | {total:>10,} / {TOTAL_DAILY_TARGET:>10,} tokens  ({total_pct:.1f}%)")
        lines.append(f"  当前引擎: {'观尘子' if self.state['current_engine']=='guanchenzi' else '星卷'}")
        lines.append(f"  本次会话: 第{self.state.get('session_count', 0)+1}次激活")
        lines.append("=" * 55)
        return "\n".join(lines)


